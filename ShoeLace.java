class ShoeLace {
	
	String color;
	double length;
	String material;
	boolean isFlat;
	String tipMaterial;
	int thickness;
	boolean elastic;
	String brand;
	boolean reflective;
	String pattern;
	
	ShoeLace() {
		
	}

	ShoeLace(String color , double length , String material , boolean isFlat , String tipMaterial , int thickness , boolean elastic , String brand , boolean reflective , String pattern) {
		this.color = color;
		this.length = length;
		this.material = material;
		this.isFlat = isFlat;
		this.tipMaterial = tipMaterial;
		this.thickness = thickness;
		this.elastic = elastic;
		this.brand = brand;
		this.reflective = reflective;
		this.pattern = pattern;
		
	}

}