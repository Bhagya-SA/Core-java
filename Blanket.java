class Blanket {

	String color;       
    double length;      
    double width;       
    String material;    
    double price;       
    boolean isWarm;
	
	Blanket(String color , double length , double width , String material , double price ,boolean isWarm ) {
		this.color = color;
		this.length = length;
		this.width = width;
		this.material = material;
		this.price = price;
		this.isWarm = isWarm;
	}
	Blanket() {
		
	}

}