class Bucket {

	String color;
	double capacity;
	String material;
	double weightInKg;
	boolean hasLid;
	
	Bucket() {
		
	}
	
	Bucket(String color , double capacity ,String material , double weightInKg , boolean hasLid) {
		this.color = color;
		this.capacity = capacity;
		this.material = material;
		this.weightInKg = weightInKg;
		this.hasLid = hasLid;
		
	}

}