class Jacket {

	String color;
	String size;
	String material;
	double price;
	boolean hasHood;
	
	Jacket() {
		
	}
	Jacket(String color , String size , String material , double price , boolean hasHood) {
		this.color = color;
		this.size = size;
		this.material = material;
		this.price = price;
		this.hasHood = hasHood;

		
	}


}